"""Turn a pg_dump of the legacy oprec tables into SQL for schema `form` (stdin -> stdout).

Keeps: CREATE TABLE, sequences, defaults, primary keys, unique constraints, indexes, foreign keys
between the three legacy tables, and the data (COPY blocks, passed through untouched).
Drops: policies, row security toggles, triggers, functions, grants, owners, extensions, and foreign
keys to auth.users. Adds: RLS on with no policies (only the service role can read), grants to
service_role.
"""
import re
import sys

TABLES = ["submissions", "recruitments", "selection_results"]
RENAME = [(re.compile(rf"\bpublic\.{t}\b"), f"form.legacy_{t}") for t in TABLES]
# Sequences/constraints/indexes named after the tables get a prefix too, to avoid clashes in `form`.
NAME_PREFIX = re.compile(rf"\bpublic\.({'|'.join(TABLES)})(_[a-z0-9_]+)\b")

DROP_STATEMENT = re.compile(
    r"^(CREATE POLICY|ALTER TABLE .* (ENABLE|DISABLE|FORCE) ROW LEVEL SECURITY|CREATE TRIGGER|"
    r"CREATE (OR REPLACE )?FUNCTION|GRANT|REVOKE|ALTER .* OWNER TO|CREATE EXTENSION|COMMENT ON|"
    r"CREATE SCHEMA|SET default_table_access_method|SELECT pg_catalog.set_config\('search_path')",
    re.IGNORECASE,
)


def rename(text: str) -> str:
    text = NAME_PREFIX.sub(lambda m: f"form.legacy_{m.group(1)}{m.group(2)}", text)
    for pattern, new in RENAME:
        text = pattern.sub(new, text)
    return text


def keep(statement: str) -> bool:
    head = statement.lstrip()
    if DROP_STATEMENT.match(head):
        return False
    if "REFERENCES auth." in statement:
        return False
    return True


out = ["-- Generated by scripts/migrate/legacy_transform.py. Review before applying.",
       "SET search_path = form, public;"]
buf = []
in_copy = False
for line in sys.stdin:
    if in_copy:
        out.append(line.rstrip("\n"))
        if line.rstrip("\n") == "\\.":
            in_copy = False
        continue
    if not buf and (line.startswith("--") or not line.strip()):
        continue
    if not buf and line.startswith("COPY "):
        out.append(rename(line.rstrip("\n")))
        in_copy = True
        continue
    buf.append(line.rstrip("\n"))
    if line.rstrip().endswith(";"):
        statement = "\n".join(buf)
        buf = []
        if keep(statement):
            out.append(rename(statement))

out.append("")
for t in TABLES:
    out.append(f"ALTER TABLE form.legacy_{t} ENABLE ROW LEVEL SECURITY;")
    out.append(f"GRANT ALL ON form.legacy_{t} TO service_role;")
out.append("GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA form TO service_role;")
print("\n".join(out))
